#!/usr/bin/env node
'use strict';
/**
 * Writes everything that is generated from lib/api-docs.js (itself synced from the Volath app):
 *   types/index.d.ts          TypeScript types: ctx, events, hooks, manifest
 *   schema/plugin.schema.json JSON Schema of plugin.json (editors validate and complete from it)
 *   docs/REFERENCE.md         every call, event, permission, manifest field, hook and limit
 *   docs/AI_GUIDE.md          what to give an AI that writes a plugin: rules + reference + examples, one file
 *   llms.txt                  where an AI should start
 *
 *   node scripts/generate.js           write the files
 *   node scripts/generate.js --check   fail when the files on disk are not what the generator would write (for CI)
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const docs = require(path.join(root, 'lib', 'api-docs.js'));
const manifestLib = require(path.join(root, 'lib', 'manifest.js'));
const pkg = require(path.join(root, 'package.json'));

const out = {};
const emit = (file, text) => { out[file] = text.replace(/\r\n/g, '\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n'; };

// ---- helpers ----------------------------------------------------------------------------------------------------------------------------

/** A type string from the docs may carry prose in parentheses ("string (ISO date)"): TypeScript gets the type, the prose a comment */
function splitType(type) {
  const notes = [];
  const clean = String(type).replace(/\b(string|number|boolean)\s*\(([^()]*)\)/g, (_, base, note) => { notes.push(note); return base; })
    .replace(/\)\s*\(([^()]*)\)/g, ')')
    // "string[] | null (null = all projects)": prose after the type
    .replace(/(\S)\s+\(([^()]*)\)\s*$/, (_, last, note) => { notes.push(note); return last; });
  return { ts: clean, note: notes.join('; ') };
}

const ident = (key) => (/^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key));
const jsdoc = (text, indent = '') => (text ? `${indent}/** ${String(text).replace(/\*\//g, '* /')} */\n` : '');
const namespaces = () => {
  const groups = {};
  for (const call of Object.values(docs.calls)) (groups[call.namespace] ||= []).push(call);
  return groups;
};

/** JSON Schema -> TypeScript (enough for plugin.json) */
function schemaToTs(node, indent = '') {
  if (!node || typeof node !== 'object') return 'unknown';
  if (node.const !== undefined) return JSON.stringify(node.const);
  if (node.enum) return node.enum.map((v) => JSON.stringify(v)).join(' | ');
  if (node.anyOf || node.oneOf) return (node.anyOf || node.oneOf).map((n) => schemaToTs(n, indent)).join(' | ');
  if (node.type === 'array') return `Array<${schemaToTs(node.items, indent)}>`;
  if (node.type === 'string') return 'string';
  if (node.type === 'integer' || node.type === 'number') return 'number';
  if (node.type === 'boolean') return 'boolean';
  if (node.type === 'object' || node.properties) {
    const props = node.properties || {};
    const keys = Object.keys(props);
    if (!keys.length) return node.additionalProperties && typeof node.additionalProperties === 'object' ? `Record<string, ${schemaToTs(node.additionalProperties, indent)}>` : 'Record<string, unknown>';
    const inner = indent + '  ';
    const lines = keys.map((k) => `${jsdoc(props[k].description, inner)}${inner}${ident(k)}${(node.required || []).includes(k) ? '' : '?'}: ${schemaToTs(props[k], inner)};`);
    return `{\n${lines.join('\n')}\n${indent}}`;
  }
  return 'unknown';
}

// ---- types/index.d.ts -------------------------------------------------------------------------------------------------------------------

function typesFile() {
  const l = [];
  l.push(`// Generated by scripts/generate.js from the Volath plugin API (api version ${docs.manifest.apiVersion}). Do not edit.`);
  l.push('// Use it in a plugin with: /** @type {import("@volath/sdk").PluginModule} */ module.exports = { ... }');
  l.push('');
  for (const [name, def] of Object.entries(docs.types)) {
    l.push(jsdoc(def.description).trimEnd());
    if (def.alias) { l.push(`export type ${name} = ${def.alias};`, ''); continue; }
    const base = def.extends ? ` extends ${def.extends}` : '';
    l.push(`export interface ${name}${base} {`);
    for (const [key, type] of Object.entries(def.fields || {})) {
      const optional = key.endsWith('?');
      const { ts, note } = splitType(type);
      if (note) l.push(`  /** ${note} */`);
      l.push(`  ${ident(key.replace(/\?$/, ''))}${optional ? '?' : ''}: ${ts};`);
    }
    l.push('}', '');
  }

  // Events
  l.push('/** The data of each event, by event name */', 'export interface VolathEventMap {');
  for (const [name, ev] of Object.entries(docs.events)) {
    l.push(jsdoc(`${ev.summary}${ev.when ? ` (${ev.when})` : ''}`, '  ').trimEnd());
    l.push(`  ${JSON.stringify(name)}: ${splitType(ev.data).ts};`);
  }
  l.push('}', '');
  l.push('export type EventName = keyof VolathEventMap;');
  l.push('export type EntityEventName = `entity.${string}.created` | `entity.${string}.updated` | `entity.${string}.deleted`;');
  l.push('export interface EntityEventData { table: string; id: string | null; row: Record<string, unknown>; changed?: string[] }');
  l.push('');
  l.push('/** What onEvent receives. A plugin never receives the events its own calls caused (`actor` says which plugin did) */');
  l.push('export interface EventEnvelope<K extends EventName | EntityEventName = EventName | EntityEventName> {');
  l.push('  event: K;', '  type: K;', '  deliveryId: string;', '  timestamp: string;');
  l.push('  project: { id: string; name?: string; customFields: CustomValues } | null;');
  l.push('  ticket: { id: string; number?: number; title?: string; customFields?: CustomValues } | null;');
  l.push('  data: K extends EventName ? VolathEventMap[K] : EntityEventData;');
  l.push("  actor: { type: 'plugin'; id: string } | null;", '}', '');

  // ctx
  l.push('export interface HttpResponse { status: number; ok: boolean; headers: Record<string, string>; body: string; json: unknown }');
  l.push('');
  l.push('export interface PluginContext {');
  l.push('  /** This plugin */', '  plugin: { id: string; version: string };');
  l.push('  /** Manifest defaults, then the general value, then the value of the current project; passwords decrypted */', '  settings: Record<string, string | number | boolean>;');
  l.push('  /** The project of the current event or ticket, otherwise null */', '  projectId: string | null;');
  l.push('  /** Writes to the plugin log in Settings › Plugins */', '  log: ((...args: unknown[]) => void) & { info(...args: unknown[]): void; warn(...args: unknown[]): void; error(...args: unknown[]): void };');
  l.push('  http: {', '    /** The only way out to the network: the host must be in permissions.network. No size limit; 55 seconds */', '    fetch(url: string, init?: { method?: string; headers?: Record<string, string>; body?: unknown }): Promise<HttpResponse>;', '  };');
  l.push('  /** Needs permissions.storage; JSON values, no size limit */', '  storage: {', '    get(key: string): Promise<unknown>;', '    set(key: string, value: unknown): Promise<void>;', '    delete(key: string): Promise<void>;', '  };');
  for (const [ns, calls] of Object.entries(namespaces())) {
    l.push(`  ${ident(ns)}: {`);
    for (const call of calls) {
      const fnName = call.name.slice(ns.length + 1);
      const params = call.params.map((p) => `${ident(p.name)}${p.optional ? '?' : ''}: ${splitType(p.type).ts}`).join(', ');
      const note = [call.summary, call.permission ? `Needs ${call.grant}` : ''].filter(Boolean).join('. ');
      l.push(jsdoc(note, '    ').trimEnd());
      l.push(`    ${ident(fnName)}(${params}): Promise<${splitType(call.returns).ts}>;`);
    }
    l.push('  };');
  }
  l.push('}', '');

  // hooks
  l.push('export interface PluginRequest { method: string; path: string; query: Record<string, unknown>; headers: Record<string, string>; body: unknown; user: { id: string; name: string; permissions: string[] } | null }');
  l.push('export interface WebhookRequest { name: string; method: string; query: Record<string, unknown>; headers: Record<string, string>; rawBody: string; body: unknown }');
  l.push('export interface PluginReply { status?: number; json?: unknown; text?: string }');
  l.push('export interface PromptRequest { stage: string; ticketId?: string }');
  l.push('');
  l.push('/** What the file named by `main` exports (CommonJS). Everything is optional */');
  l.push('export interface PluginModule {');
  l.push('  /** After the process starts, and again after the settings are saved */', '  onLoad?(ctx: PluginContext): void | Promise<void>;');
  l.push('  /** For each event in permissions.events */', '  onEvent?(event: EventEnvelope, ctx: PluginContext): void | Promise<void>;');
  l.push('  /** The plugin page or a slot calls volath.api(path, init) */', '  onRequest?(req: PluginRequest, ctx: PluginContext): PluginReply | unknown | Promise<PluginReply | unknown>;');
  l.push('  /** An outside system calls /api/plugin-hooks/<id>/<name> with the right secret */', '  onWebhook?(req: WebhookRequest, ctx: PluginContext): PluginReply | void | Promise<PluginReply | void>;');
  l.push('  /** Text to append to an AI prompt (never replaces it); return a string, or nothing */', '  onPrompt?(request: PromptRequest, ctx: PluginContext): string | void | Promise<string | void>;');
  l.push('  /** Handlers of `schedule` entries, by the name given in the manifest */', '  tasks?: Record<string, (ctx: PluginContext) => void | Promise<void>>;');
  l.push('}', '');
  l.push('/** plugin.json */');
  l.push(`export interface PluginManifest ${schemaToTs(docs.manifest.schema)}`);
  l.push('');
  l.push(`export declare const API_VERSION: number;`);
  return l.join('\n');
}

// ---- docs/REFERENCE.md ------------------------------------------------------------------------------------------------------------------

function referenceFile() {
  const l = [];
  const code = (s) => '`' + String(s).replace(/`/g, "'") + '`';
  l.push('# Volath plugin reference', '');
  l.push(`Generated from the Volath plugin API, api version ${docs.manifest.apiVersion}. Everything below exists; nothing else does.`, '');

  l.push('## Limits', '');
  for (const [k, v] of Object.entries(docs.limits)) l.push(`- **${k}**: ${typeof v === 'object' ? JSON.stringify(v) : v}`);
  l.push('');

  l.push('## Permissions', '');
  l.push('A plugin asks for what it needs in `permissions` of `plugin.json`; the administrator sees each line in plain words and must accept them. A permission with levels includes the lower ones (`read` < `write` < `admin`).', '');
  l.push('| Permission | Meaning |', '|---|---|');
  for (const [name, def] of Object.entries(docs.manifest.schema.properties.permissions.properties)) l.push(`| ${code(name)} | ${String(def.description || '').replace(/|/g, '/')} |`);
  l.push('');

  l.push('## plugin.json', '');
  for (const rule of docs.manifest.rules || []) l.push(`- ${rule}`);
  l.push('', 'The JSON Schema is in `schema/plugin.schema.json`. Fields:', '');
  const props = docs.manifest.schema.properties || {};
  for (const [key, def] of Object.entries(props)) {
    const required = (docs.manifest.schema.required || []).includes(key) ? ' (required)' : '';
    l.push(`- ${code(key)}${required}: ${def.description || ''}`);
  }
  l.push('');

  l.push('## What a plugin code file exports', '');
  for (const [name, h] of Object.entries(docs.hooks)) {
    if (name === 'description') { l.push(h, ''); continue; }
    l.push(`### ${code(name)}`, '', `${code(h.signature || name)}`, '');
    if (h.when) l.push(`- When: ${h.when}`);
    if (h.request) l.push(`- Request: ${code(h.request)}`);
    if (h.returns) l.push(`- Returns: ${h.returns}`);
    if (h.notes) l.push(`- ${h.notes}`);
    l.push('');
  }

  l.push('## ctx', '', docs.ctx.description, '');
  for (const [name, m] of Object.entries(docs.ctx.members)) l.push(`- ${code('ctx.' + name)}: ${code(m.type)}. ${m.description}`);
  l.push('');

  l.push('## Calls', '');
  for (const [ns, calls] of Object.entries(namespaces())) {
    l.push(`### ctx.${ns}`, '');
    for (const call of calls) {
      const params = call.params.map((p) => `${p.name}${p.optional ? '?' : ''}: ${p.type}`).join(', ');
      l.push(`#### ${code(`ctx.${call.name}(${params})`)}`, '');
      l.push(`${call.summary}`, '');
      l.push(`- Returns: ${code(call.returns)}`);
      l.push(`- Needs: ${call.grant}${call.changesData ? ' (counts toward the writes per minute)' : ''}`);
      for (const p of call.params) if (p.description) l.push(`- ${code(p.name)}: ${p.description}`);
      if (call.notes) l.push(`- ${call.notes}`);
      if (call.example) l.push('', '```js', call.example, '```');
      l.push('');
    }
  }

  l.push('## Events', '');
  l.push('Every event arrives as an envelope:', '');
  l.push(docs.envelope.description, '');
  for (const [k, v] of Object.entries(docs.envelope.fields)) l.push(`- ${code(k)}: ${v}`);
  l.push('');
  for (const [name, ev] of Object.entries(docs.events)) {
    l.push(`### ${code(name)}`, '', `${ev.summary}${ev.when ? ` (${ev.when})` : ''}`, '', `- data: ${code(ev.data)}`);
    if (ev.notes) l.push(`- ${ev.notes}`);
    l.push('');
  }
  const ee = docs.entityEvents;
  l.push(`### ${code(ee.pattern)}`, '', ee.summary, '', `- data: ${code(ee.data)}`);
  for (const n of [].concat(ee.notes || [])) l.push(`- ${n}`);
  l.push('');

  l.push('## Types', '');
  for (const [name, def] of Object.entries(docs.types)) {
    l.push(`### ${name}`, '', def.description || '', '');
    if (def.alias) { l.push('```ts', `type ${name} = ${def.alias}`, '```', ''); continue; }
    l.push('```ts', `interface ${name}${def.extends ? ' extends ' + def.extends : ''} {`);
    for (const [key, type] of Object.entries(def.fields || {})) l.push(`  ${key.replace(/\?$/, '')}${key.endsWith('?') ? '?' : ''}: ${type};`);
    l.push('}', '```', '');
  }
  return l.join('\n');
}

// ---- docs/AI_GUIDE.md -------------------------------------------------------------------------------------------------------------------

function aiGuideFile() {
  const intro = fs.readFileSync(path.join(root, 'templates', 'ai-guide-intro.md'), 'utf8');
  const examples = [];
  const exDir = path.join(root, 'examples');
  for (const id of fs.readdirSync(exDir).sort()) {
    const dir = path.join(exDir, id);
    if (!fs.statSync(dir).isDirectory()) continue;
    examples.push(`### Example: ${id}`, '', '`plugin.json`', '', '```json', fs.readFileSync(path.join(dir, 'plugin.json'), 'utf8').trim(), '```', '');
    for (const f of fs.readdirSync(dir)) {
      if (f === 'plugin.json' || !/\.(js|html)$/.test(f)) continue;
      examples.push(`\`${f}\``, '', '```' + (f.endsWith('.html') ? 'html' : 'js'), fs.readFileSync(path.join(dir, f), 'utf8').trim(), '```', '');
    }
  }
  return [intro.trim(), '', '---', '', referenceFile().replace(/^# .*\n/, '').replace(/^Generated from.*\n/m, ''), '', '---', '', '## Working examples', '', ...examples].join('\n');
}

// ---- go ----------------------------------------------------------------------------------------------------------------------------------

emit('types/index.d.ts', typesFile());
emit('schema/plugin.schema.json', JSON.stringify(docs.manifest.schema, null, 2));
emit('docs/REFERENCE.md', referenceFile());
emit('docs/AI_GUIDE.md', aiGuideFile());
emit('llms.txt', [
  '# Volath plugin SDK',
  '',
  '> Build plugins for Volath (project and ticket management with AI development). A plugin is a zip with a plugin.json and optionally a Node file; it asks for permissions and reacts to events or acts on Volath through ctx.',
  '',
  '- [AI guide](docs/AI_GUIDE.md): everything needed to write a plugin: rules, the full reference and working examples. Read this first',
  '- [Reference](docs/REFERENCE.md): every call, event, permission, manifest field and limit',
  '- [TypeScript types](types/index.d.ts)',
  '- [plugin.json schema](schema/plugin.schema.json)',
  '- [Examples](examples)',
].join('\n'));

const check = process.argv.includes('--check');
let stale = 0;
for (const [file, text] of Object.entries(out)) {
  const target = path.join(root, file);
  if (check) {
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : null;
    if (current !== text) { console.error(`stale: ${file}`); stale++; }
  } else {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, text);
    console.log(`wrote ${file}`);
  }
}
if (check && stale) { console.error('Run npm run build and commit the result.'); process.exit(1); }
